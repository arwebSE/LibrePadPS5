"""Embed the verified adapter firmware; runtime loading remains adapter-only."""
import hashlib
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIRMWARE_SHA256 = "48084d9fa53b9bb04358f3bb127b7495dc8f7bb0b3ca1437bd24ef2b6eabdf66"


def main():
    data = (ROOT / "vendor/xbox/FW_ACC_00U.bin").read_bytes()
    if len(data) != 70620 or hashlib.sha256(data).hexdigest() != FIRMWARE_SHA256:
        raise SystemExit("Bundled Xbox firmware does not match the verified image")
    ilm, dlm = struct.unpack_from("<II", data)
    if not ilm or not dlm or 32 + ilm + dlm != len(data):
        raise SystemExit("Invalid bundled Xbox firmware memory lengths")
    output = ROOT / "build/generated/xbox/firmware_blob.h"
    output.parent.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by tools/embed_xbox_firmware.py. */",
             "static const uint8_t XBOX_FIRMWARE[] = {"]
    lines += ["    " + ",".join(f"0x{b:02x}" for b in data[i:i+16]) + ","
              for i in range(0, len(data), 16)]
    output.write_text("\n".join(lines) + "\n};\n", encoding="ascii")


if __name__ == "__main__":
    main()
