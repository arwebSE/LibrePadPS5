"""Check local documentation links and active C/C++ include paths."""
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

root = Path(__file__).resolve().parents[1]
include_dirs = [root / name for name in ("src", "vendor", "vendor/anypad", "tests", "tests/stubs")]
failures = []

for folder in ("src", "tests", "vendor"):
    for path in (root / folder).rglob("*"):
        if path.suffix not in {".c", ".cpp", ".h"}:
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            match = re.match(r'\s*#\s*include\s*"([^"]+)"', line)
            if not match:
                continue
            name = match[1]
            if name == "dashboard/assets.h":  # Generated by tools/embed_dashboard.py.
                continue
            if not any((base / name).is_file() for base in [path.parent, *include_dirs]):
                failures.append(f"{path.relative_to(root)}:{number}: missing include {name}")

documents = [root / "README.md", root / "src/README.md", root / "vendor/anypad/README.md", root / "vendor/xow/README.md"]
documents += list((root / "docs").rglob("*.md"))
for path in documents:
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        for match in re.finditer(r'\[[^\]]*\]\(([^)]+)\)', line):
            target = match[1].strip("<>")
            url = urlsplit(target)
            if url.scheme or not url.path:
                continue
            if not (path.parent / unquote(url.path)).exists():
                failures.append(f"{path.relative_to(root)}:{number}: missing link {target}")

if failures:
    raise SystemExit("\n".join(failures))
print("Active includes and local documentation links passed")
