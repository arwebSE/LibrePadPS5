"""Generate C assets from editable web sources; no runtime filesystem required."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
output = root / "build/generated/dashboard/assets.h"
output.parent.mkdir(parents=True, exist_ok=True)
assets = [("PAGE", "index.html"), ("DASHBOARD_CSS", "dashboard.css"),
          ("DASHBOARD_JS", "dashboard.js"), ("FAVICON", "favicon.svg")]
content = ["/* Generated by tools/embed_dashboard.py. Edit web/ instead. */"]
for name, filename in assets:
    content.append(f"static const char {name}[] =")
    content.extend(json.dumps(line, ensure_ascii=True)
                   for line in (root / "web" / filename).read_text(encoding="utf-8").splitlines(keepends=True))
    content.append(";")
output.write_text("\n".join(content) + "\n", encoding="utf-8")
