"""Generate C assets from editable web sources; no runtime filesystem required."""
import json
import hashlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
web = root / "web"
bundle = web / "dist"
manifest = json.loads((bundle / "source-manifest.json").read_text(encoding="utf-8"))
sources = {path.relative_to(web).as_posix() for folder in ("src", "public")
           for path in (web / folder).rglob("*") if path.is_file() and not path.name.endswith(".test.js")}
sources.update({"index.html", "package.json", "package-lock.json", "vite.config.js", "scripts/build.mjs"})
stale = sources != set(manifest["sources"])
def checksum(path):
    data = path.read_bytes()
    if path.suffix in {".js", ".vue", ".css", ".mjs", ".html", ".json", ".svg"}:
        data = data.replace(b"\r", b"")
    return hashlib.sha256(data).hexdigest()
for folder, entries in ((web, manifest["sources"]), (bundle, manifest["assets"])):
    for name, digest in entries.items():
        path = folder / name
        stale |= not path.is_file() or checksum(path) != digest
if stale:
    raise SystemExit("Dashboard bundle is stale. Run npm --prefix web ci, then npm --prefix web run build.")
output = root / "build/generated/dashboard/assets.h"
output.parent.mkdir(parents=True, exist_ok=True)
assets = [("PAGE", "index.html"), ("DASHBOARD_CSS", "dashboard.css"),
          ("DASHBOARD_JS", "dashboard.js"), ("FAVICON", "favicon.svg")]
content = ["/* Generated by tools/embed_dashboard.py. Edit web/src and rebuild web/dist. */"]
def c_literal(data):
    # Fixed-width octal preserves UTF-8 bytes; escaped '?' prevents C trigraphs
    # in minified JavaScript (for example nullish coalescing followed by a quote).
    escapes = {34: '\\"', 92: '\\\\', 63: '\\?'}
    return '"' + ''.join(escapes.get(byte, chr(byte) if 32 <= byte < 127 else f"\\{byte:03o}")
                         for byte in data) + '"'
for name, filename in assets:
    content.append(f"static const char {name}[] =")
    data = (bundle / filename).read_bytes().replace(b"\r", b"")
    content.extend(c_literal(data[offset:offset+512]) for offset in range(0, len(data), 512))
    content.append(";")
output.write_text("\n".join(content) + "\n", encoding="utf-8")
